const MESSAGES: Record<Lang, Record<BuilderKey, string>> = { en, fi, sv };

export function bt(lang: Lang, key: BuilderKey, vars: Record<string, string | number> = {}) {
  return MESSAGES[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
